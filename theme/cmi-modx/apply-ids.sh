#!/usr/bin/env bash
# ============================================================
# Замена условных ID ресурсов [[~1]], [[~2]] ... на реальные
# ID, которые MODX присвоит вашим ресурсам.
#
# Использование (из папки cmi-modx):
#   1) создайте ресурсы в MODX, запишите их реальные ID;
#   2) впишите их в MAP ниже (плейсхолдер -> реальный ID);
#   3) предпросмотр:   ./apply-ids.sh
#      применить:      ./apply-ids.sh --apply
#
# Затрагивает файлы в templates/ и chunks/. Делает .bak-копии.
# Литералы в home.tpl (&parents=`2` каталог, `3` бренды) правьте
# вручную — это параметры сниппетов, а не ссылки [[~N]].
# ============================================================
set -euo pipefail

# Плейсхолдер => реальный ID ресурса. Замените правые значения.
declare -A MAP=(
  [1]=1     # Главная
  [2]=2     # Каталог (корень)
  [3]=3     # Бренды
  [12]=12   # Доставка и оплата
  [13]=13   # Магазины
  [14]=14   # Избранное
  [15]=15   # Корзина
  [16]=16   # Профиль (кабинет)
  [17]=17   # Вход
  [18]=18   # Регистрация
  [19]=19   # Гарантия и возврат
  [20]=20   # Рассрочка и кредит
  [21]=21   # Помощь / FAQ
  [22]=22   # Контакты
  [23]=23   # О нас
  [24]=24   # Новости
  [25]=25   # Блог
  [26]=26   # Сотрудничество
  [27]=27   # Политика конфиденциальности
  [28]=28   # Пользовательское соглашение
  [29]=29   # Распродажа
  [30]=30   # Ноты
  [31]=31   # Комплекты
)

APPLY="${1:-}"
mapfile -t FILES < <(grep -rl '\[\[~' templates chunks 2>/dev/null || true)

for ph in "${!MAP[@]}"; do
  real="${MAP[$ph]}"
  [ "$ph" = "$real" ] && continue
  for f in "${FILES[@]}"; do
    if grep -q "\[\[~${ph}\]\]\|\[\[~${ph}?" "$f"; then
      if [ "$APPLY" = "--apply" ]; then
        sed -i.bak -E "s/\[\[~${ph}(\]\]|\?)/[[~${real}\1/g" "$f"
        echo "applied [[~${ph}]] -> [[~${real}]] in $f"
      else
        echo "would replace [[~${ph}]] -> [[~${real}]] in $f"
      fi
    fi
  done
done

[ "$APPLY" = "--apply" ] && echo "Готово. Проверьте diff, удалите .bak при необходимости." || echo "Предпросмотр. Запустите с --apply для применения."
